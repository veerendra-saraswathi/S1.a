"""Regenerate the gateway's golden MAVLink frames from pymavlink, the reference implementation.

The Go parser's tests decode these bytes and compare against the values below, so the
parser is checked against an independent encoder rather than against itself.

    uv run tools/mavlink-sim/gen_golden.py > gateways/mavlink-gateway/internal/mavlink/testdata/golden.txt
"""

from __future__ import annotations

import math

from pymavlink.dialects.v10 import common as v1
from pymavlink.dialects.v20 import common as v2


class _Sink:
    def write(self, _: bytes) -> None:
        pass


def frames(dialect, tag: str):
    mav = dialect.MAVLink(_Sink(), srcSystem=7, srcComponent=1)
    yield f"heartbeat_{tag}", mav.heartbeat_encode(
        dialect.MAV_TYPE_QUADROTOR, dialect.MAV_AUTOPILOT_ARDUPILOTMEGA, 0x80 | 0x01, 3, dialect.MAV_STATE_ACTIVE
    )
    yield f"gcs_heartbeat_{tag}", mav.heartbeat_encode(
        dialect.MAV_TYPE_GCS, dialect.MAV_AUTOPILOT_INVALID, 0, 0, dialect.MAV_STATE_ACTIVE
    )
    yield f"sys_status_{tag}", mav.sys_status_encode(0, 0, 0, 235, 24310, 1250, 76, 0, 0, 0, 0, 0, 0)
    yield f"sys_status_unknown_{tag}", mav.sys_status_encode(0, 0, 0, 0, 65535, -1, -1, 0, 0, 0, 0, 0, 0)
    yield f"gps_raw_int_{tag}", mav.gps_raw_int_encode(1_000_000, 3, 174401000, 783489000, 580000, 80, 120, 500, 9000, 14)
    yield f"attitude_{tag}", mav.attitude_encode(1000, math.radians(10), math.radians(-5), math.radians(90), 0, 0, 0)
    yield f"global_position_int_{tag}", mav.global_position_int_encode(
        1000, 174401000, 783489000, 580500, 40250, 300, 400, -150, 8700
    )
    yield f"global_position_no_heading_{tag}", mav.global_position_int_encode(1000, 0, 0, 0, 0, 0, 0, 0, 65535)
    yield f"vfr_hud_{tag}", mav.vfr_hud_encode(13.5, 12.0, 87, 55, 580.5, 1.5)
    yield f"battery_status_{tag}", mav.battery_status_encode(
        0, 1, 1, 3150, [4050] * 6 + [65535] * 4, 1250, 900, -1, 76
    )
    # Message 32 (LOCAL_POSITION_NED) is valid MAVLink the gateway does not decode.
    yield f"undecoded_{tag}", mav.local_position_ned_encode(1000, 1, 2, 3, 0, 0, 0)


def main() -> None:
    print("# name hex   (generated by tools/mavlink-sim/gen_golden.py from pymavlink; do not edit)")
    for dialect, tag in ((v1, "v1"), (v2, "v2")):
        mav = dialect.MAVLink(_Sink(), srcSystem=7, srcComponent=1)
        for name, message in frames(dialect, tag):
            print(name, message.pack(mav).hex())


if __name__ == "__main__":
    main()
