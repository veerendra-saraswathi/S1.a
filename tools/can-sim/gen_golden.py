"""Regenerate the CAN gateway's golden frames from the dronecan package, the reference encoder.

The Go decoder's tests read these candump log lines and compare against the values
below, so it is checked against an independent implementation rather than itself.

    uv run tools/can-sim/gen_golden.py > gateways/can-gateway/internal/dronecan/testdata/golden.log
"""

from __future__ import annotations

import math

import dronecan
from dronecan import uavcan
from dronecan.transport import Transfer

T0_US = 1_795_600_000_000_000  # 2026-11-25T09:46:40Z; frames are 1 ms apart from here


def frames(msg, node: int, tid: int, priority: int = 16) -> list[tuple[int, bytes]]:
    transfer = Transfer(payload=msg, source_node_id=node, transfer_id=tid, transfer_priority=priority)
    return [(f.message_id, bytes(f.bytes)) for f in transfer.to_frames()]


def cases():
    yield "node_status", frames(
        uavcan.protocol.NodeStatus(uptime_sec=1234, health=1, mode=2, sub_mode=5, vendor_specific_status_code=0xBEEF),
        node=10, tid=3,
    )
    yield "actuator_status", frames(  # 8 bytes: two frames
        uavcan.equipment.actuator.Status(actuator_id=3, position=0.25, force=-1.5, speed=2.0, power_rating_pct=40),
        node=10, tid=4,
    )
    yield "actuator_status_unmeasured", frames(
        uavcan.equipment.actuator.Status(actuator_id=4, position=-0.5, force=math.nan, speed=math.nan, power_rating_pct=0),
        node=10, tid=5,
    )
    yield "esc_status", frames(  # 14 bytes: three frames
        uavcan.equipment.esc.Status(
            error_count=7, voltage=24.5, current=12.25, temperature=313.15, rpm=-12345, power_rating_pct=55, esc_index=2
        ),
        node=20, tid=6,
    )
    command = uavcan.equipment.actuator.Command
    yield "array_command", frames(
        uavcan.equipment.actuator.ArrayCommand(
            commands=[command(actuator_id=3, command_type=1, command_value=0.5),
                      command(actuator_id=4, command_type=1, command_value=-0.25)]
        ),
        node=1, tid=7,
    )
    # Valid DroneCAN the gateway does not decode: an AHRS solution.
    yield "undecoded", frames(uavcan.equipment.ahrs.MagneticFieldStrength(magnetic_field_ga=[0.1, 0.2, 0.3]), node=10, tid=8)
    # A service request (GetNodeInfo, node 1 asking node 10): not a message, ignored.
    request = Transfer(
        payload=uavcan.protocol.GetNodeInfo.Request(), source_node_id=1, dest_node_id=10,
        transfer_id=9, transfer_priority=16, service_not_message=True, request_not_response=True,
    )
    yield "service_request", [(f.message_id, bytes(f.bytes)) for f in request.to_frames()]


def main() -> None:
    print("# name candump-log-line   (generated by tools/can-sim/gen_golden.py from dronecan; do not edit)")
    t = T0_US
    for name, encoded in cases():
        for can_id, data in encoded:
            t += 1000
            print(f"{name} ({t // 1_000_000}.{t % 1_000_000:06d}) can0 {can_id:08X}#{data.hex().upper()}")
    # An 11-bit frame from something else on the bus: ignored.
    t += 1000
    print(f"standard_id ({t // 1_000_000}.{t % 1_000_000:06d}) can0 123#DEADBEEF")


if __name__ == "__main__":
    _ = dronecan  # the import registers the DSDL types used above
    main()
